export type Coordinates = { lat: number; lon: number };
export type Place = {
  id: string;
  label: string;
  coordinates: Coordinates;
  addressLine?: string;
  category?: string | null;
  city?: string | null;
  country?: string | null;
  source?: string;
  sourceRecord?: string;
  sourceUrl?: string;
  sourceQuery?: string;
  checkedAt?: string;
  confidence?: number | null;
};
export type FareEstimate = {
  currency: "PHP";
  min: number | null;
  max: number | null;
  status: "published_rule" | "estimated" | "unknown";
  sourceName: string | null;
  sourceUrl: string | null;
  checkedAt: string | null;
};
export type GeoLine = { type: "LineString"; coordinates: [number, number][] };
export type GeoGeometry = GeoLine | { type: "MultiLineString"; coordinates: [number, number][][] };
export type RouteStep = { instruction: string; distanceMeters: number | null; durationSeconds: number | null };
export type TravelMode = "walk" | "drive";
export type RouteLeg = {
  mode: TravelMode;
  title: string;
  distanceMeters: number | null;
  durationSeconds: number | null;
  geometry: GeoGeometry | null;
  steps: RouteStep[];
  source: string | null;
};
export type TransportOption = {
  id: string;
  title: string;
  mode: TravelMode;
  legs: RouteLeg[];
  fare: FareEstimate;
  totalDurationSeconds: number | null;
  totalWalkingMeters: number | null;
  transfers: number | null;
  availability: "verified_route" | "estimated_road_route" | "unknown";
  note: string | null;
  rankingEligible: { cheapest: boolean; fastest: boolean };
};
export type CompareRequest = { origin: Place; destination: Place };
export type CompareResponse = {
  origin: Place;
  destination: Place;
  generatedAt: string;
  scope: "davao_city" | "unsupported";
  options: TransportOption[];
  warnings: string[];
};
export type PlaceSuggestion = Place & { addressLine: string; category: string | null; source: "Geoapify" | "Wandr Davao landmark index"; confidence: number | null };
export type ApiError = { error: { code: string; message: string; retryable: boolean } };
